//! The JACL shell's image (jacl_impl#204): the runtime with the compiler linked in, so that
//! `[repl-eval SRC]` compiles a line in the shell and runs it in the shell's own domain, on the §22
//! Jit capability (`codegen/selfhost/repl/`).
//!
//! The image is the runtime as [`crate::translate_runtime`] builds it, with `JACL_REPL`, and the
//! emit-only frontend, codegen and the REPL's bridge and C library, llvm-linked into one unit. The
//! frontend's own value runtime defines two names jaclrt does, so the frontend is compiled with its
//! copies renamed ([`RENAMED`]). A line's unit imports the runtime by name, bound against a table
//! of every `jacl_*` function the runtime defines, generated here from the runtime's IR.

use std::path::{Path, PathBuf};
use std::process::Command;

const ROOT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../..");

/// The functions both the frontend and jaclrt define: the frontend's are renamed, as the units a
/// line compiles to import jaclrt's.
const RENAMED: [&str; 2] = ["jacl_arr_new", "jacl_eq"];

/// Functions a unit may import that the bridge defines, beside the runtime's `jacl_*`.
const BRIDGE: [&str; 2] = ["synrt_str_empty", "synrt_str_push_byte"];

fn clang(src: &str, out: &Path, opt: &str, flags: &[String]) {
    let status = Command::new("clang")
        .args([
            opt,
            "-S",
            "-emit-llvm",
            "-fno-vectorize",
            "-fno-slp-vectorize",
            "-w",
        ])
        .arg("--target=x86_64-unknown-linux-gnu")
        .args(flags)
        .arg(src)
        .arg("-o")
        .arg(out)
        .status()
        .expect("spawn clang (is clang installed?)");
    assert!(status.success(), "clang failed to compile {src}");
}

/// The names of the functions `ll` defines that a unit may import: `jacl_*`, not internal.
fn runtime_functions(ll: &Path) -> Vec<String> {
    let text = std::fs::read_to_string(ll).expect("read the runtime's IR");
    let mut names: Vec<String> = text
        .lines()
        .filter(|l| {
            l.starts_with("define ") && !l.contains(" internal ") && !l.contains(" private ")
        })
        .filter_map(|l| {
            let at = l.find(" @")? + 2;
            let end = at + l[at..].find('(')?;
            Some(l[at..end].trim_matches('"').to_string())
        })
        .filter(|n| n.starts_with("jacl_"))
        .collect();
    names.sort();
    names.dedup();
    names
}

/// The symbol table `__vm_jit_compile_linked` binds a unit's imports against: each name's table
/// slot, the function's address. Each address is passed to `slot` as a pointer, which the on-ramp
/// lowers to `ref.func`: an address cast to an integer in place becomes a constant, and one in
/// static data stays as written, and either names the function before it once the image is given
/// its entry (temen#2308).
fn symtab_source(names: &[String]) -> String {
    let mut s = String::from(
        "/* Generated by runtime/harness/src/repl.rs: every runtime function a REPL line's unit may\n \
         * import, by name, with its table slot. */\n\
         typedef unsigned long u64;\n",
    );
    for n in names {
        s.push_str(&format!("extern void {n}(void);\n"));
    }
    s.push_str(
        "static void uleb(unsigned char *o, u64 cap, u64 *p, u64 v) {\n\
         \x20 do { unsigned char b = v & 0x7f; v >>= 7; if (v) b |= 0x80; if (*p < cap) o[*p] = b; (*p)++; } while (v);\n\
         }\n\
         __attribute__((noinline)) static u64 slot(void (*f)(void)) { return (u64)f; }\n\
         static void put(unsigned char *o, u64 cap, u64 *p, const char *n, u64 len, u64 slot) {\n\
         \x20 uleb(o, cap, p, len);\n\
         \x20 for (u64 i = 0; i < len; i++) { if (*p < cap) o[*p] = (unsigned char)n[i]; (*p)++; }\n\
         \x20 if (*p < cap) o[*p] = 0; /* kind 0: a table slot */\n\
         \x20 (*p)++;\n\
         \x20 uleb(o, cap, p, slot);\n\
         }\n\
         u64 jacl_repl_symtab(unsigned char *o, u64 cap) {\n\
         \x20 u64 p = 0;\n",
    );
    s.push_str(&format!("  uleb(o, cap, &p, {});\n", names.len()));
    for n in names {
        s.push_str(&format!(
            "  put(o, cap, &p, \"{n}\", {}, slot({n}));\n",
            n.len()
        ));
    }
    s.push_str("  return p;\n}\n");
    s
}

/// The shell's runtime, translated: jaclrt and unir's unit, the compiler, and the REPL.
pub fn translate_shell_runtime() -> temen_llvm::Translated {
    let tag = format!("{}_{:?}", std::process::id(), std::thread::current().id());
    let tag: String = tag
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect();
    let dir = std::env::temp_dir().join(format!("jacl_shell_{tag}"));
    std::fs::create_dir_all(&dir).expect("a scratch directory");
    let out = |name: &str| -> PathBuf { dir.join(name) };
    let runtime = format!("{ROOT}/runtime");
    let codegen = format!("{ROOT}/codegen");

    let rt = out("rt.ll");
    let rt_flags = ["-DNDEBUG", "-DJACL_UNIR", "-DJACL_REPL", "-I", &runtime].map(String::from);
    clang(&format!("{runtime}/jaclrt.c"), &rt, "-O2", &rt_flags);

    // As codegen/selfhost/build_compiler_temen.sh builds the compiler for a guest.
    let mut fe: Vec<String> = [
        "-std=c99",
        "-D_DEFAULT_SOURCE",
        "-D_POSIX_C_SOURCE=200809L",
        "-D__EMSCRIPTEN__",
        "-DJACL_EMIT_ONLY",
        "-Wno-implicit-function-declaration",
    ]
    .map(String::from)
    .to_vec();
    fe.extend([
        "-I".into(),
        codegen.clone(),
        "-I".into(),
        format!("{codegen}/selfhost/inc"),
    ]);
    fe.extend(RENAMED.iter().map(|n| format!("-D{n}=fe_{n}")));
    let mut cli = fe.clone();
    cli.push("-Dmain=jacl_cli_main".into());
    let units = [
        (format!("{codegen}/tests/emit_jacl.c"), "fe.ll", &cli),
        (format!("{codegen}/codegen.c"), "cg.ll", &fe),
        (format!("{codegen}/irbuilder.c"), "irb.ll", &fe),
        (
            format!("{codegen}/selfhost/repl/repl_guest.c"),
            "repl.ll",
            &fe,
        ),
        (
            format!("{codegen}/selfhost/repl/repl_libc.c"),
            "libc.ll",
            &fe,
        ),
    ];
    for (src, name, flags) in &units {
        clang(src, &out(name), "-O2", flags);
    }

    let mut names = runtime_functions(&rt);
    names.extend(BRIDGE.iter().map(|n| n.to_string()));
    std::fs::write(out("symtab.c"), symtab_source(&names)).expect("write the symbol table");
    clang(
        &out("symtab.c").to_string_lossy(),
        &out("symtab.ll"),
        "-O0",
        &[],
    );

    let linked = out("shell.ll");
    let llvm_link = std::env::var("LLVM_LINK").unwrap_or_else(|_| "llvm-link-21".into());
    let status = Command::new(&llvm_link)
        .arg("-S")
        .arg(&rt)
        .arg(format!("{runtime}/unir/unir_cabi.ll"))
        .args(units.iter().map(|(_, name, _)| out(name)))
        .arg(out("symtab.ll"))
        .arg("-o")
        .arg(&linked)
        .status()
        .unwrap_or_else(|e| panic!("spawn {llvm_link} (LLVM 21+ llvm-link; set LLVM_LINK): {e}"));
    assert!(
        status.success(),
        "{llvm_link} failed to link the shell's runtime"
    );
    let t =
        temen_llvm::translate_ll_path(&linked).expect("temen-llvm: translate the shell's runtime");
    let _ = std::fs::remove_dir_all(&dir);
    t
}

/// The JACL program at `path` linked with the shell's runtime: a child image a vat spawns
/// (`child`), or a root program; and its window's size, log2.
pub fn shell_image(path: &Path, child: bool) -> Result<(temen_ir::Module, u8), String> {
    crate::link_image(crate::emit_program(path)?, translate_shell_runtime(), child)
}
